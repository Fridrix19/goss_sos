const ticketCounters = {
  content: 0,
  pid: 0
};

const ticketElement = document.querySelector("#ticket");
const generateButton = document.querySelector("#generateTicket");

function getSelectedDirectionKey() {
  return document.querySelector('input[name="direction"]:checked').value;
}

function getRandomItem(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function createQuestion(group) {
  const questionText = getRandomItem(group.questions);
  const questionIndex = group.questions.indexOf(questionText);

  return {
    group: group.title,
    section: group.section,
    number: group.startNumber + questionIndex,
    text: questionText
  };
}

function createTicket(directionKey) {
  const direction = directions[directionKey];
  const isitGroup = direction.groups.find(
    (group) => group.title === "Информационные системы и технологии"
  );
  const secondQuestionGroups = direction.groups.filter((group) => group !== isitGroup);

  return [createQuestion(isitGroup), createQuestion(getRandomItem(secondQuestionGroups))];
}

function clearTicket() {
  const direction = directions[getSelectedDirectionKey()];

  ticketElement.innerHTML = `
    <div class="ticket__empty">
      <p>Выбрано направление «${direction.title}». Нажмите кнопку, чтобы получить билет только из вопросов этого направления.</p>
    </div>
  `;
}

function renderTicket() {
  const directionKey = getSelectedDirectionKey();
  const direction = directions[directionKey];
  ticketCounters[directionKey] += 1;
  const questions = createTicket(directionKey);

  ticketElement.innerHTML = `
    <div class="ticket__header">
      <div>
        <h2 class="ticket__title">Билет #${ticketCounters[directionKey]}</h2>
        <p class="ticket__direction">${direction.title} — ${direction.subtitle}</p>
      </div>
      <span class="badge badge--accent">1-й вопрос всегда ИСИТ</span>
    </div>
    <div class="questions">
      ${questions
        .map(
          (question, index) => `
            <article class="question-card">
              <div class="question-card__meta">
                <span class="badge">Вопрос ${index + 1}</span>
                <span class="badge">№ ${question.section ? `${question.section}.` : ""}${question.number}</span>
                <span class="badge badge--accent">${question.group}</span>
              </div>
              <p class="question-card__text"><strong>${question.number}.</strong> ${question.text}</p>
            </article>
          `
        )
        .join("")}
    </div>
  `;
}

generateButton.addEventListener("click", renderTicket);
document
  .querySelectorAll('input[name="direction"]')
  .forEach((input) => input.addEventListener("change", clearTicket));
